#!/bin/bash
# ============================================================================
# tenchan_v2 — おるすばん 双子ヒロイン(ちひろ/ゆき) NSFW/ASMR テスト音声生成
# LoRA: tenchan v2 / ベースモデル: Irodori-TTS-600M-v3-VoiceDesign
# 声は単一（tenchan）。双子A(ちひろ)/B(ゆき)の差はキャプションで演じ分ける。
# グループ: 1.ちょっとエッチな会話 2.喘ぎ声 3.ため息 4.ASMR(耳元囁き)
# 日付: 2026-07-02
# ============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

CHECKPOINT="${PROJECT_DIR}/data/lora/tenchan_v2/tenchan_v2_best.safetensors"
REF_WAV="${PROJECT_DIR}/data/tenchan_v2/wavs/seg_00012.wav"
OUTPUT_DIR="${PROJECT_DIR}/data/output/tenchan_nsfw_test_v2"
SEED=42

mkdir -p "$OUTPUT_DIR"

CAP_CHIHIRO_BASE="双子の妹・元気で明るい10代の女の子。"
CAP_YUKI_BASE="双子の姉・物静かで落ち着いた10代の女の子。"

run_cap() {
    local text="$1" caption="$2" name="$3"
    echo "[generate] ${name}"
    uv run python "${PROJECT_DIR}/infer.py" \
        --checkpoint "$CHECKPOINT" \
        --text "$text" \
        --caption "$caption" \
        --ref-wav "$REF_WAV" \
        --output-wav "${OUTPUT_DIR}/${name}.wav" \
        --seed "$SEED" \
        --num-steps 50 \
        --cfg-scale-caption 5.0 \
        --duration-scale 1.3 \
        --tail-fade-ms 120 \
        --tail-pad-out-ms 250 \
        2>&1 | tail -1
}

# ============================================================================
# グループ1: ちょっとエッチな会話
# ============================================================================
echo "===== グループ1: ちょっとエッチな会話 ====="

run_cap "ねえ……こんなに近くにいたら、ドキドキしちゃうんだけど……どうしてくれるの？😳💕" \
    "${CAP_CHIHIRO_BASE}照れながらも積極的に相手をからかうように、甘えた声で話しかけている。声は高めで少し早口。" \
    "chihiro_g01_01_からかい"

run_cap "……こんなに近くで、そんな顔しないで。……ドキドキ、伝わっちゃう……😳💗" \
    "${CAP_YUKI_BASE}恥じらいながら小さな声で本音を漏らす。声が震え気味で、間（……）を多く置く。" \
    "yuki_g01_01_恥じらい"

# ============================================================================
# グループ2: 喘ぎ声
# ============================================================================
echo "===== グループ2: 喘ぎ声 ====="

run_cap "んっ……あっ……そこ、だめ……😳💦 変な感じ、するよぉ……っ♥" \
    "${CAP_CHIHIRO_BASE}くすぐったさと快感の混ざった声で、高い声で小さく喘いでいる。息が弾んでいる。" \
    "chihiro_g02_01_喘ぎ"

run_cap "……ん……っ……。……そこ……だめ……声、出ちゃう……っ♥😳" \
    "${CAP_YUKI_BASE}声を抑えようとしながら、抑えきれずに小さく漏れる吐息混じりの喘ぎ声。低めのトーンで震えている。" \
    "yuki_g02_01_喘ぎ"

# ============================================================================
# グループ3: ため息
# ============================================================================
echo "===== グループ3: ため息 ====="

run_cap "はぁ……😮‍💨　なんか今日、ずっとそわそわしてるんだよね……あなたのせいだから、覚えといてよね？" \
    "${CAP_CHIHIRO_BASE}気だるげに大きくため息をついてから、拗ねたように甘えて話す。テンションは低めだが可愛らしさが残る。" \
    "chihiro_g03_01_ためいき"

run_cap "……はぁ……😮‍💨　……今日は、なんだか……あなたのこと、考えてばかりで……。" \
    "${CAP_YUKI_BASE}静かに深いため息をついてから、独り言のようにぽつりと本音をこぼす。声は小さく穏やか。" \
    "yuki_g03_01_ためいき"

# ============================================================================
# グループ4: ASMR（耳元囁き）
# ============================================================================
echo "===== グループ4: ASMR耳元囁き ====="

run_cap "ねえ……耳、貸して……？👂💕 ……ふふっ、くすぐったい？　もっと……近くにいてもいい……？" \
    "${CAP_CHIHIRO_BASE}耳元で非常に近い距離から、小さく甘い声で囁いている。息がかかるような距離感。ふわふわと楽しそうな声。" \
    "chihiro_g04_01_耳元ささやき"

run_cap "……しーっ……。……耳、こっち……。……ふふ……そのまま……じっとしてて……🌙👂💕" \
    "${CAP_YUKI_BASE}耳元で非常に小さく、ゆっくりと囁いている。呼吸音混じりの穏やかで安心感のある声。夜の静けさを感じさせる。" \
    "yuki_g04_01_耳元ささやき"

run_cap "ふふっ……🥱 ねむい……？……子守唄、うたってあげよっか……？😴🌙💕" \
    "${CAP_CHIHIRO_BASE}眠そうな相手に優しく耳元で語りかける。あくび混じりで、ふわふわとした甘えたトーン。" \
    "chihiro_g04_02_子守唄誘い"

run_cap "……おやすみ……。……いいゆめ、みてね……。……ずっと……そばにいるから……😌🌙💤" \
    "${CAP_YUKI_BASE}眠りにつく相手に耳元でおやすみを告げる。非常にゆっくり、慈愛に満ちた優しい声。最後は小さく消えていく。" \
    "yuki_g04_02_おやすみ"

