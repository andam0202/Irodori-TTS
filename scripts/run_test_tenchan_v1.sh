    "$CAP_YUKI" "yuki_01_出迎え"

run_cap "……ふふ。水曜日は、私。……ゆっくり、お話ししましょうね" \
    "$CAP_YUKI" "yuki_02_微笑み"

run_cap "ただいま。……ふふ、二人とも、楽しかったみたいね。……それじゃ、夕飯作っちゃうね" \
    "$CAP_YUKI" "yuki_03_帰宅家事"

run_cap "……顔が赤いわよ。何も言わなくても分かる。……お風呂、長かったし" \
    "$CAP_YUKI" "yuki_04_からかい"

run_cap "おはよう。……ちひろは、今日は友達とプールに行ってるの。……二人きりだね" \
    "$CAP_YUKI" "yuki_05_二人きり"

