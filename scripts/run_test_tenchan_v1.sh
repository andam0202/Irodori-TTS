CAP_CHIHIRO="双子の妹・元気で明るい10代の女の子。親しい相手に楽しそうに、早口でハキハキと話しかけている。テンションが高く、感情表現が豊かで声が高め。"
CAP_YUKI="双子の姉・物静かで落ち着いた10代の女の子。言葉数が少なく、間（……）を置きながらゆっくり囁くように話す。感情を控えめに、優しく穏やかな低めのトーン。"

# ============================================================================
