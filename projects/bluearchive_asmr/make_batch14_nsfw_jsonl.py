def seed_of(text: str) -> int:
    return int(hashlib.md5(text.encode()).hexdigest()[:8], 16) % 100000


def main() -> None:
    outdir = REPO / "projects/bluearchive_asmr/jsonl"
    outdir.mkdir(parents=True, exist_ok=True)
    all_lines = []
    for sp, (ckpt, ref) in CHARS.items():
        for kind, text, caption in BATCH14[sp]:
            out = DESKTOP / sp / "nsfw" / f"{sp}_{kind}.wav"
            all_lines.append({
                "text": text, "caption": caption,
                "checkpoint": str(ckpt), "ref_wav": str(ref),
                "out_path": str(out), "seed": seed_of(text + sp + kind + "b14"),
                "duration_scale": 1.35, "tail_fade_ms": 120, "tail_pad_out_ms": 250,
            })
    (outdir / "_batch14_nsfw_all.jsonl").write_text(
        "\n".join(json.dumps(o, ensure_ascii=False) for o in all_lines) + "\n", encoding="utf-8")
    print(f"batch14(nsfw): {len(all_lines)} lines -> _batch14_nsfw_all.jsonl")


if __name__ == "__main__":
    main()
